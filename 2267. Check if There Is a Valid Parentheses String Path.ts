function hasValidPath(grid: string[][]): boolean {
  // console.log(grid)

  const n = grid.length
  const m = grid[0].length

  if ((n+m) % 2 === 0) {
    return false
  }

  if (grid[0][0] === ")") {
    return false
  }

  const maxOpen = (n+m-1)/2
  const res: number[][][] = new Array(n)

  for(let i = 0 ; i<n; i++) {
    res[i] = new Array(m)
  }

  res[0][0] = [1]

  for(let j = 1; j<m;j++) {
    res[0][j] = res[0][j-1].map(x => x + (grid[0][j] === "(" ? 1 : -1)).filter(x => x >= 0 && x <= maxOpen)
  }

  for(let i = 1; i< n; i++) {
    res[i][0] = res[i-1][0].map(x => x + (grid[i][0] === "(" ? 1 : -1)).filter(x => x >= 0 && x <= maxOpen)
  }

  for(let i = 1 ; i<n; i++) {
    for(let j = 1; j<m;j++) {
      let val1 = res[i][j-1].map(x => x + (grid[i][j] === "(" ? 1 : -1)).filter(x => x >= 0 && x <= maxOpen)
      let val2 = res[i-1][j].map(x => x + (grid[i][j] === "(" ? 1 : -1)).filter(x => x >= 0 && x <= maxOpen)
      res[i][j] = [...new Set([...val1, ...val2])]
    }
  }

  return res[n-1][m-1].length > 0 && res[n-1][m-1].some(x => x === 0)
}

